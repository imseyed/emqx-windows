#!/usr/bin/env bash

## Build the crc32cer NIF on Windows.
##
## crc32cer's compile hook is guarded to "(linux|darwin|solaris|freebsd)", so
## nothing is built here, and its NIF is not optional: crc32cer:init/0 raises
## crc32cer_nif_not_found from on_load, which in an embedded release aborts
## the kernel application and the node never boots.
##
## Upstream drives the build from CMakeLists.txt, which is Unix-shaped: it
## passes -fPIC to the google/crc32c sub-build, links libcrc32c.a and stdc++,
## and applies a patch with the `patch` command. google/crc32c itself supports
## MSVC (it has _MSC_VER branches for __cpuid and _mm_prefetch), so this skips
## CMake and hands the sources to cl.exe, with the config header that CMake
## would otherwise generate written out directly.
##
## Run with the crc32cer dependency directory as the working directory, which
## is what rebar3 does for a hook.

set -euo pipefail

# Keep MSYS2 from rewriting cl.exe's arguments as paths.
export MSYS2_ARG_CONV_EXCL='*'

CRC32C_REPO="${CRC32C_REPO:-https://github.com/google/crc32c.git}"
## The tag CMakeLists.txt pins for the ExternalProject.
CRC32C_TAG="${CRC32C_TAG:-1.1.2}"

BUILD_DIR="c_build"
CRC32C_DIR="${BUILD_DIR}/external/crc32c"
CONFIG_DIR="${BUILD_DIR}/config"
OBJ_DIR="${BUILD_DIR}/obj"
OUT_DLL="priv/libcrc32cer_nif.dll"

if [ ! -f c_src/crc32c_nif.c ]; then
    echo "ERROR: run this from the crc32cer dependency directory (no c_src/crc32c_nif.c here: $(pwd))" >&2
    exit 1
fi

## EMQX_WIN_NIF_IDEMPOTENT: the dependency is pinned, so once the NIF is built
## there is nothing to rebuild. Both the pre-build in patch-native-deps.sh and
## the rebar3 hook call this script, and a forced rebuild is FORCE=1.
if [ -f "priv/libcrc32cer_nif.dll" ] && [ "${FORCE:-0}" != "1" ]; then
    echo "crc32cer: priv/libcrc32cer_nif.dll is already built (FORCE=1 to rebuild)"
    exit 0
fi

for tool in cl.exe link.exe git; do
    command -v "$tool" >/dev/null || {
        echo "ERROR: $tool not on PATH; source scripts/windows/build-env.sh first" >&2
        exit 1
    }
done

win() { cygpath -w -a "$1"; }

ERL_ROOT="$(erl -noshell -eval 'io:format("~s",[code:root_dir()]), halt().')"
ERTS_INCLUDE="$(cygpath -w "${ERL_ROOT}/usr/include")"

## 1. google/crc32c sources
if [ ! -f "${CRC32C_DIR}/src/crc32c.cc" ]; then
    mkdir -p "$(dirname "${CRC32C_DIR}")"
    rm -rf "${CRC32C_DIR}"
    git clone --depth 1 --branch "${CRC32C_TAG}" "${CRC32C_REPO}" "${CRC32C_DIR}"
fi

## 2. the header CMake would have configured from src/crc32c_config.h.in.
##    x86-64 MSVC: little endian, no GCC builtins, both X86 intrinsics present,
##    no ARM, no getauxval (that is a Linux/Android thing), tests off.
mkdir -p "${CONFIG_DIR}/crc32c"
cat > "${CONFIG_DIR}/crc32c/crc32c_config.h" <<'HEADER'
#ifndef CRC32C_CRC32C_CONFIG_H_
#define CRC32C_CRC32C_CONFIG_H_

/* Generated by scripts/windows/build-crc32cer.sh for x86-64 MSVC. */

#define BYTE_ORDER_BIG_ENDIAN 0
#define HAVE_BUILTIN_PREFETCH 0
#define HAVE_MM_PREFETCH 1
#define HAVE_SSE42 1
#define HAVE_ARM64_CRC32C 0
#define HAVE_STRONG_GETAUXVAL 0
#define HAVE_WEAK_GETAUXVAL 0
#define CRC32C_TESTS_BUILT_WITH_GLOG 0

#endif  /* CRC32C_CRC32C_CONFIG_H_ */
HEADER

## 3. compile
mkdir -p "${OBJ_DIR}" priv

crc_inc="$(win "${CRC32C_DIR}/include")"
cfg_inc="$(win "${CONFIG_DIR}")"
src_inc="$(win "${CRC32C_DIR}/src")"

crc_srcs=()
for c in crc32c.cc crc32c_portable.cc crc32c_sse42.cc crc32c_arm64.cc; do
    crc_srcs+=("$(win "${CRC32C_DIR}/src/${c}")")
done
nif_src="$(win c_src/crc32c_nif.c)"

echo "crc32cer: compiling google/crc32c and the NIF with cl.exe"
# Paths are resolved above: cl.exe drops its .obj files in the working
# directory, so the compile runs from the obj dir.
( cd "${OBJ_DIR}" && cl.exe /nologo /c /O2 /MD /EHsc /std:c++14 \
    -I"${crc_inc}" -I"${cfg_inc}" -I"${src_inc}" \
    "${crc_srcs[@]}" )

( cd "${OBJ_DIR}" && cl.exe /nologo /c /O2 /MD \
    -I"${crc_inc}" -I"${cfg_inc}" -I"${ERTS_INCLUDE}" \
    "${nif_src}" )

link.exe /nologo /DLL "$(win "${OBJ_DIR}")\*.obj" /OUT:"$(win "${OUT_DLL}")"

echo "crc32cer: built ${OUT_DLL}"
